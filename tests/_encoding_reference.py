def lebel_folds(X, Y, story_ids, alpha_grid, per_voxel_alpha, n_splits=5, random_state=0):
    """``LeBel2023Encoding.__call__``, the fold loop."""
    held_out = np.full(Y.shape, np.nan, dtype=np.float32)
    chosen_alphas = []
    for train_mask, test_mask in run_kfold_masks(story_ids, n_splits, random_state):
        fitter = (_ridge_per_voxel_alpha if per_voxel_alpha else _ridge_grouped_alpha)
        fold_prediction, alpha = fitter(
            X[train_mask], Y[train_mask], X[test_mask],
            story_ids[train_mask], alpha_grid, random_state=random_state)
        held_out[test_mask] = fold_prediction
        chosen_alphas.append(
            np.median(alpha).item() if np.ndim(alpha) else float(alpha))
    return pearson_summary(Y, held_out), chosen_alphas
