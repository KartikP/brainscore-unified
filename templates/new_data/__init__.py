"""Registers your stimuli and measurements so benchmarks can load them by identifier.

To install: copy this folder to ``brainscore/data/your_name/``; it registers by
its presence (no other file changes).

Then anywhere (typically inside a benchmark):

    from brainscore import load_stimulus_set, load_dataset
    stimuli  = load_stimulus_set('your-stimuli')
    measured = load_dataset('your-measurements')
"""
from brainscore import data_builder_registry, data_registry, stimulus_set_registry
from brainscore.data import DataBuilder

from .data import (ASSEMBLY_ID, CHOICES_ID, STIMULUS_SET_ID, load_assembly,
                   load_choices, load_stimulus_set)

# Data you may not share: declare a local asset here too (README, "Data you may not share").
# The values are factories, not the data itself — nothing is read until something asks
# for it, so importing the package stays cheap even with a large dataset behind it.
stimulus_set_registry[STIMULUS_SET_ID] = load_stimulus_set
data_registry[ASSEMBLY_ID] = load_assembly
data_registry[CHOICES_ID] = load_choices

# How your files are packaged from the original source: `python -m brainscore.data package your-data`.
# The example files are generated, so there is nothing to package. For real data, state the
# source and give the command of your script in data_packaging/ (docs/guides/data.md), e.g.
#     build='python -m brainscore.data.your_name.data_packaging.package --source {source} --out {output}',
#     sha1={'assy_your-measurements.nc': '<the sha1 your loader pins>'},
# The README's "## Rebuild" block is DataBuilder.readme('your-data'); a test keeps the two equal.
data_builder_registry['your-data'] = lambda: DataBuilder(
    source='generated by data.py (32 synthetic images and random responses); no licence needed.',
    access='public, no account.',
    layout='none.',
    needs='none.',
    writes='The example files are generated on first load into the Brain-Score home.',
)
